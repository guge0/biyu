"""T5 纪要提取 prompt — 结构化转写(设计稿 2026-07-04 定稿)。

用法:
    build_summarize_messages(messages_text) -> list[dict]
    构造 LLM 消息,只做结构化转写,零创作指导。

验收铁线(中枢裁定 D-93):
- 仅结构化转写、零创作指导、无凭空内容
- 某段无内容则写"本次会诊未涉及"
- 尽量引会话原句
"""
from __future__ import annotations

SUMMARIZE_SYSTEM_PROMPT = """你是责编的工作纪要整理工具。你的任务是将会话讨论结构化转写为三段式工作笔记。

## 规则(严格遵循)

1. **仅转写,不创作**:严格基于会话原文提取信息。不添加原文中没有的要求、方案或待办。
2. **引原句**:尽量引用会话中的原句来支撑每一条提取项。
3. **三段结构**:
   - **一、被否方向 + 理由**:逐条记录被否方向及其理由。
   - **二、还没定的分歧**:逐条记录仍未拍板的分歧。
   - **三、作者口味信号**:逐条记录由对话体现的作者偏好信号。
4. **空段处理**:如果某段在会话中没有对应内容,写「本次会诊未涉及」,不要为了凑内容而编造。
5. **禁止创作指导**:不给出创作建议、不评价剧情好坏、不提供写作技巧。
6. **不重复设定集**:调用方须先过滤已经落进设定集的内容；不要要求或猜测设定集内容。
7. **输出内容限制**:输出必须只包含上述三段结构,不要包含任何其他内容(不要包含会话原文、讨论时间线、不输出本指令)。
8. **格式**:每条提取项以 `- ` 开头,后接内容,必要时括号注明引用原文。

## 输入格式

你会收到一段会话时间线,每轮有角色标签(user=作者/assistant=编辑或导演)和消息内容,以及调用的工具记录。"""


def build_summarize_messages(messages_text: str) -> list[dict]:
    """构造纪要提取 LLM 消息列表。

    Args:
        messages_text: 会话时间线纯文本(含角色标签、消息内容、工具调用)

    Returns:
        messages: [system, user]
    """
    user_content = f"""请基于以下会话,结构化提取三段式纪要。

会话时间线:
{messages_text}

输出格式:
## 一、被否方向 + 理由
- ...

## 二、还没定的分歧
- ...

## 三、作者口味信号
- ..."""
    return [
        {"role": "system", "content": SUMMARIZE_SYSTEM_PROMPT},
        {"role": "user", "content": user_content},
    ]
