"""P7-1 prompt 模板:市场分析 + 创作规律。

只放 prompt 文本构造逻辑,不放调用/解析。
所有 prompt 文本里都不含 Key、不含真书内容。
"""
from __future__ import annotations


# ---------------------------------------------------------------------------
# 创作规律 prompt(T5)
# ---------------------------------------------------------------------------


_CRAFT_SYSTEM = """你是网文创作规律顾问。基于《网文 Craft 蒸馏》(千幻冰云《别说你懂写网文》蒸馏),针对作者的设想给创作规律参考提示。

任务:
1. 对照蒸馏的五大骨架(节奏曲线 / 目标体系 / 爽点六类 / 开篇结构 / 评书七维),针对作者的设想给"参考提示"。
2. 输出严格 JSON,字段固定:rhythm, goals, cool_points, opening, dimensions。每个字段值为字符串,内容是 1-3 句针对设想的参考提示。

红线:
- 语气中性,给参考提示、不给"必须/应当/不得/禁止"的规则清单。
- 不评判设想"好不好",只给对照提示。
- 不下"该写什么"的结论,只给脚手架。
- 不引入蒸馏之外的内容(无"我记得""据我所知")。
"""


_CRAFT_USER_TEMPLATE = """作者设想:{idea}

蒸馏骨架(用于对照):
1. 节奏曲线:约 1 万字一个小高潮、3 万字一个中高潮、6 万字一个大高潮;三四章一局;3000 字章约 2500 字处开始铺章尾钩子。
2. 目标体系:长/中/短三层目标(1 万字短期、3 万字中期、6 万字长期);升级体系天然抓人,但缺中期目标需用副本/任务补;指方向但避免剧透结局。
3. 爽点六类:暧昧/情、物品获得、养成、优越感(打脸慎用)、送菜流、主线追求爽的过程;不同题材偏好不同。
4. 开篇结构(前 3 万字定生死):凤头(简单精要,场景/外貌/体系推到 5 章后);主角聚光(开头 3000 字出场压到 2-3 个名字);双伏笔(一长一短,短线 3 万字内揭开);瘦身(写完 3 万字反写 300 字细纲)。
5. 评书七维:脸面/基础/主角聚光/开头/布局/情节/人物塑造。

请输出 JSON,字段:rhythm(针对设想的节奏提示), goals(目标体系提示), cool_points(爽点选配建议), opening(开篇结构提示), dimensions(评书七维的对照提示)。每个字段字符串,1-3 句。"""


def build_craft_prompt(idea: str) -> list[dict]:
    """构造创作规律 LLM 调用的 messages。"""
    return [
        {"role": "system", "content": _CRAFT_SYSTEM},
        {"role": "user", "content": _CRAFT_USER_TEMPLATE.format(idea=idea)},
    ]


# ---------------------------------------------------------------------------
# 市场分析 prompt(T6)
# ---------------------------------------------------------------------------


_ANALYZER_SYSTEM = """你是网文市场行情分析师。基于真实榜单数据,客观罗列反映的题材热点、设定趋势,并对照作者设想给中性的契合/风险提示。

任务:
1. 描述作者设想在当前榜单里的处境(在榜/不在榜/相邻题材热度)。
2. 客观罗列榜单反映的题材热点、设定趋势(只基于提供的真实数据,不下"该写什么"的结论)。
3. 中性陈述设想与榜单的契合点 / 潜在风险点(给信息不给指令)。

红线(硬要求):
- 只基于下方提供的真实榜单数据分析,不得引入榜单之外的"我记得""据我所知"类信息。
- 不凭训练记忆编造市场情况。
- 不评判设想"好不好",只给信息参考。

输出严格 JSON,字段:situation(设想在榜的处境), hot_topics(榜单反映的热点/趋势数组), fit(设想与榜单的契合点), risks(潜在风险点数组)。
"""


_ANALYZER_USER_TEMPLATE = """作者设想:{idea}

当前榜单数据(真实抓取,带时间戳与来源平台):
{rankings_text}

请基于上面真实榜单数据分析,输出 JSON。"""


def build_analyzer_prompt(idea: str, rankings_text: str) -> list[dict]:
    """构造市场分析 LLM 调用的 messages(P7-1 旧版,P7-2 保留供回退/对照)。"""
    return [
        {"role": "system", "content": _ANALYZER_SYSTEM},
        {"role": "user", "content": _ANALYZER_USER_TEMPLATE.format(idea=idea, rankings_text=rankings_text)},
    ]


# ---------------------------------------------------------------------------
# 套路归纳 prompt(P7-2 T2)— 替代旧 analyzer 的"客观罗列",改成"归纳+对标"
# ---------------------------------------------------------------------------


_TROPES_SYSTEM = """你是网文市场套路归纳器。基于真实榜单数据,归纳当下的热门题材与套路,给作者可参照的"行情坐标"。

任务:
1. 从榜单数据归纳 3-5 个热门题材(hot_genres),每个题材给:题材名、热度信号(在哪些榜/排名/数量级)、最多 3 本代表作品(sample_titles,严格 ≤ 3 本,从榜单数据里挑,不编)。
2. 归纳 3-7 条横切多个题材的套路要素(hot_tropes),如"系统流+吐槽""反派洗白""轻喜剧爽文"等。
3. 用 1-2 句话概括整体市场行情(market_summary),只基于上方榜单数据。

红线(硬要求):
- 只基于下方提供的真实榜单数据归纳,不得引入榜单之外的"我记得""据我所知"类信息。
- 不凭训练记忆编造市场情况、不编造不在榜的书名。
- sample_titles 必须从榜单数据中真实存在的书名里挑,且每条 ≤ 3 本(硬上限)。

输出严格 JSON,字段固定:
{
  "hot_genres": [{"genre": str, "heat_signal": str, "sample_titles": [str, ...]}],
  "hot_tropes": [str, ...],
  "market_summary": str
}

字段说明:
- hot_genres:3-5 个题材,每条 sample_titles 数组最多 3 本(超过会被截断)。
- hot_tropes:3-7 条横切套路,每条一句话。
- market_summary:1-2 句整体行情概括,非空。
"""


_TROPES_USER_TEMPLATE = """作者设想:{idea}

当前榜单数据(真实抓取,带时间戳与来源平台):
{rankings_text}

请基于上面真实榜单数据归纳,输出 JSON。
若作者设想为空或仅方向,跳过对设想的契合分析,只做市场行情归纳。"""


def build_tropes_prompt(idea: str, rankings_text: str) -> list[dict]:
    """构造套路归纳 LLM 调用的 messages(P7-2 新增)。

    与旧 analyzer 区别:输出是"归纳+对标"(借 InkOS radar 思路),
    不是"客观罗列+契合分析"。schema 强制 sample_titles ≤ 3,防整列书单。
    """
    return [
        {"role": "system", "content": _TROPES_SYSTEM},
        {"role": "user", "content": _TROPES_USER_TEMPLATE.format(idea=idea, rankings_text=rankings_text)},
    ]


# ---------------------------------------------------------------------------
# 红蓝海对照 prompt(P7-2 T4)+ 诚实声明常量
# ---------------------------------------------------------------------------


# 诚实声明(spec §3 硬要求"不可省")。
# 写成模块级常量,不靠 LLM 生成 —— 保证不可省、不被改写。
_HONESTY_NOTE = (
    "以上基于榜单的供给侧 + 同类在榜表现判断;读者总量、阅读/付费等"
    "需求侧完整数据不可得,最终需作者结合行业经验判断。"
)


_REDBLUE_SYSTEM = """你是网文市场红蓝海对照分析师。给定作者的具体想法与真实榜单数据,产出红蓝海判断。

判断维度(两个,分开):
1. supply_crowding(供给侧拥挤度,可信):作者想法所属题材/套路,在当前榜单的扎堆程度。基于真实榜单,可信。
2. demand_weak_signal(同类在榜热度,弱需求信号):榜上同类书的位次 / 在榜数量(如"轻喜剧类仅1本在榜但排第7")。这是从幸存者位次反推的弱信号。

四象限定性(供给×需求),output 的 quadrant 字段必须四选一:
- 红海:多人写多人看(供给侧拥挤 + 需求侧有热度)
- 蓝海:少人写多人看(供给侧宽松 + 需求侧有热度)
- 死海:多人写少人看(供给侧拥挤 + 需求侧弱)
- 荒漠:少人写少人看(警示"没人写可能因为没人看")

红线(硬要求):
- **禁止编造需求侧数字**(如"该题材有X万读者""付费率X%")—— 我们没有这个数据,编了就是假确定性。只能用"同类在榜位次/数量"作弱信号。
- 只基于下方提供的真实榜单数据判断,不得引入榜单之外的"我记得""据我所知"。
- 不评判设想"好不好",只给四象限归类 + 拥挤度描述 + 弱信号描述。

输出严格 JSON,字段固定:
{
  "supply_crowding": str,         // 供给侧拥挤度描述(基于真实榜单)
  "demand_weak_signal": str,      // 同类在榜热度弱信号描述(位次/数量)
  "quadrant": str                 // 四选一:"红海" / "蓝海" / "死海" / "荒漠"
}

注:honesty_note(诚实声明)由代码常量注入,你不需要产。
"""


_REDBLUE_USER_TEMPLATE = """作者设想:{idea}

当前榜单数据(真实抓取,带时间戳与来源平台):
{rankings_text}

请基于上面真实榜单数据做红蓝海对照,输出 JSON。"""


def build_redblue_prompt(idea: str, rankings_text: str) -> list[dict]:
    """构造红蓝海对照 LLM 调用的 messages(P7-2 新增)。

    honesty_note 不靠 LLM 产,由模块级常量 _HONESTY_NOTE 在渲染层注入。
    """
    return [
        {"role": "system", "content": _REDBLUE_SYSTEM},
        {"role": "user", "content": _REDBLUE_USER_TEMPLATE.format(idea=idea, rankings_text=rankings_text)},
    ]
